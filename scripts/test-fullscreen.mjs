import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
const source = await readFile(new URL('../lib/fullscreen.ts', import.meta.url), 'utf8');
const exports = {};
const document = { documentElement: {} };
runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports, document });
const { requestMediaFullscreen } = exports;
let nativeCalls = 0;
const video = { webkitEnterFullscreen() { nativeCalls++; } };
assert.equal(await requestMediaFullscreen({}, video), 'native-video', 'iPhone uses real fullscreen by default');
assert.equal(nativeCalls, 1);
assert.equal(await requestMediaFullscreen({}, video, true), 'viewport', 'laser mode keeps overlays on iPhone');
assert.equal(nativeCalls, 1, 'laser mode never enters video-only fullscreen');
let stageCalls = 0;
assert.equal(await requestMediaFullscreen({ async requestFullscreen() { stageCalls++; } }, video), 'document');
assert.equal(stageCalls, 1, 'standard fullscreen retains mode button');
assert.equal(await requestMediaFullscreen({ async requestFullscreen() { throw new Error(); } }, video), 'native-video');
assert.equal(await requestMediaFullscreen({}, { async requestFullscreen() {} }), 'document');
assert.equal(await requestMediaFullscreen({}, { webkitEnterFullscreen() { throw new Error(); } }), 'viewport');
document.documentElement.requestFullscreen = async () => {};
assert.equal(await requestMediaFullscreen({}, video, true), 'document');
document.documentElement.requestFullscreen = async () => { throw new Error(); };
assert.equal(await requestMediaFullscreen({}, null, true), 'viewport');
console.log('PASS: mobile native fullscreen, laser overlay mode, standard API and unsupported browser fallbacks');
